// Generates assets/css/theme.css: the "editorial" theme layer that sits
// between Atomic Age (tokens.css + bundle.css) and site.css.
//
// Atomic Age only switches to dark through prefers-color-scheme. The site
// also has a manual light/dark toggle, so this file restates every themed
// color token under :root[data-theme=light] and :root[data-theme=dark]
// (read straight from tokens.css, so it never drifts from the system), then
// layers the editorial palette and type on top: warm near-black ink, a
// darker coral accent that passes AA on cream, DM Sans for UI and body text,
// and a light-weight Fraunces for display. Re-run after build-tokens.mjs.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const tokensCss = readFileSync(path.join(ROOT, "assets/atomic-age/tokens.css"), "utf8");

const vars = (block) =>
  Object.fromEntries([...block.matchAll(/--([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));

const darkStart = tokensCss.indexOf("@media (prefers-color-scheme: dark)");
const light = vars(tokensCss.slice(0, darkStart));
const dark = vars(tokensCss.slice(darkStart));
const themed = Object.keys(dark); // every token the dark theme overrides

const editorial = {
  light: {
    surface: "#f1ede7",
    "surface-raised": "#faf7f4",
    ink: "#151312",
    "ink-secondary": "#5c554d",
    "ink-muted": "#645e56",
    accent: "#b4432a",
    "accent-hover": "#9a3822",
    "on-accent": "#ffffff",
    "accent-soft": "#f3dcd3",
  },
  dark: {
    surface: "#151312",
    "surface-raised": "#211e1c",
    "surface-sunken": "#0d0c0b",
    ink: "#f3ece0",
    "ink-secondary": "#b8b0a4",
    "ink-muted": "#9e978f",
    accent: "#e8674a",
    "accent-hover": "#f07d61",
    "on-accent": "#151312",
  },
};

const block = (base, over) =>
  themed.map((name) => `  --${name}: ${over[name] ?? base[name]};`).join("\n");

const css = `/* Generated by scripts/build-theme.mjs. Do not hand-edit. */

:root {
  --font-sans: "DM Sans", system-ui, -apple-system, "Segoe UI", sans-serif;
  --font-body: "DM Sans", system-ui, -apple-system, "Segoe UI", sans-serif;
}

:root, :root[data-theme="light"] {
  color-scheme: light;
${block(light, editorial.light)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${block(dark, editorial.dark).replace(/^/gm, "  ")}
  }
}

:root[data-theme="dark"] {
  color-scheme: dark;
${block(dark, editorial.dark)}
}
`;

writeFileSync(path.join(ROOT, "assets/css/theme.css"), css);
console.log(`Wrote assets/css/theme.css (${themed.length} themed tokens)`);
